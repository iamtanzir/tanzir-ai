-- Supabase / Postgres schema for Mr.Robot "Learn" corrections.
-- Run once in the Supabase SQL editor.

create table if not exists public.evolutions (
  id         bigint generated by default as identity primary key,
  profile_id text        not null,
  topic      text        not null,
  topic_key  text        not null,
  correction text        not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (profile_id, topic_key)
);

create index if not exists evolutions_profile_updated_idx
  on public.evolutions (profile_id, updated_at desc);

-- Only the server-side API (service role key) reads and writes this table.
-- The anon key is never used, so enable RLS and add no public policies.
alter table public.evolutions enable row level security;

